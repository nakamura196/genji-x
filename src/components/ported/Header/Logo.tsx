/**
 * ロゴ。**源氏香の図**を描く。
 *
 * ── なぜこの図案か ──────────────────────────────────────────────
 * 源氏香は、5 種類の香を焚いて同じ香りの組み合わせを当てる遊び。
 * その答えを **5 本の縦線と、同じ組と判じた線をつなぐ横線**で表す。
 * 組み合わせは 52 通りあり、源氏物語の第2帖から第53帖の巻名が当てられている。
 *
 * **54 帖を扱うこの目録の標として、これ以上ふさわしい図案は無い。**
 * 縦線 5 本は資料の列を、横線は「同じものと判じた」という校異の営みを思わせる。
 *
 * ── 前のロゴがなぜ崩れて見えたか ────────────────────────────────
 * 縦線を 4 本しか描いていなかった。源氏香の図は **5 本でなければ成立しない**。
 * 画面で見て初めて「線の断片」に見えることに気づいた。
 * 図案の意味を確かめずに描いていた。
 *
 * ── 描き方 ──────────────────────────────────────────────────────
 * 香は右から左へ数える。ここでは第2帖「帚木」の図
 * （右の 2 本が同じ組、左の 3 本が同じ組）を使う。目録の最初の帖に当たる図で、
 * 左右の対称が崩れすぎず、小さくしても形が残る。
 */
export function Logo({ size = 32 }: { size?: number }) {
  // 5 本の縦線。右から左へ x = 27, 21, 15, 9, 3
  const xs = [27, 21, 15, 9, 3];
  const top = 6;
  const bottom = 27;
  const bar = 10; // 横線の高さ

  return (
    <svg
      width={size} height={size} viewBox="0 0 30 32"
      role="img" aria-label="Genji-X"
      style={{ display: 'block' }}
    >
      <g
        stroke="var(--menu-logo-color, currentColor)"
        strokeWidth="1.8"
        strokeLinecap="round"
        fill="none"
      >
        {xs.map((x) => <line key={x} x1={x} y1={top} x2={x} y2={bottom} />)}
        {/* 右の 2 本をつなぐ */}
        <line x1={xs[0]} y1={bar} x2={xs[1]} y2={bar} />
        {/* 左の 3 本をつなぐ */}
        <line x1={xs[2]} y1={bar} x2={xs[4]} y2={bar} />
      </g>
    </svg>
  );
}
